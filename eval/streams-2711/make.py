PITCH = {1: 1.0, 2: 0.92, 3: 1.08, 4: 0.86, 5: 1.14}
GAIN = {5: 0.3}  # guest 5 speaks quietly (about -10 dB)
# 5 speakers: each group's 3 roles rotate over guests 1-5
G = [[(((gu - 1 + gi) % 5) + 1, r, t) for gu, r, t in lines] for gi, lines in enumerate(G)]


def clip(k, guest, text):
    os.makedirs("/tmp/protokol-eval", exist_ok=True)
    raw = f"/tmp/protokol-eval/r2-{k}.wav"
    subprocess.run(["say", "-v", "Lesya", "--data-format=LEI16@48000", "-o", raw, text], check=True)
    w = wave.open(raw); x = array.array("h", w.readframes(w.getnframes())); w.close()
    f = PITCH[guest]
    if f != 1.0:  # resample: plays f times faster/higher at 48 kHz
        n = int(len(x) / f)
        x = array.array("h", (x[min(len(x) - 1, int(i * f))] for i in range(n)))
    if guest in GAIN:
        x = array.array("h", (int(v * GAIN[guest]) for v in x))
    out = wave.open(f"clips/o{k}.wav", "wb"); out.setnchannels(1); out.setsampwidth(2); out.setframerate(48000); out.writeframes(x.tobytes()); out.close()
    return len(x) / 48000


rows = []; k = 0; total = 0.0; words_all = words_ov = 0; spans_all = []
t_group = 0.0
for g, lines in enumerate(G, 1):
    starts, ends = [], []
    for guest, rule, text in lines:
        k += 1
        d = clip(k, guest, text)
        if rule[0] == "new":
            s = 0.0
        elif rule[0] == "before_end":
            s = max(0.0, ends[rule[1]] - rule[2])
        else:
            s = starts[rule[1]] + rule[2]
        starts.append(s); ends.append(s + d)
        rows.append((g, guest, round(s, 2), text, d))
    for (guest, rule, text), s, e in zip(lines, starts, ends):
        ws = text.split()
        for i in range(len(ws)):
            t = s + (e - s) * (i + .5) / len(ws)
            words_all += 1
            words_ov += any(o_s <= t <= o_e for (o_s, o_e) in zip(starts, ends) if (o_s, o_e) != (s, e))
    total += max(ends) + 1.0
with open("overlap.tsv", "w") as f:
    for g, guest, s, text, _ in rows:
        f.write(f"{g}\t{guest}\t{s}\t{text}\n")
print(f"{len(G)} groups, {k} clips, ~{total/60:.1f} min, words {words_all}, overlapped {words_ov} ({100*words_ov/words_all:.0f}%)")
